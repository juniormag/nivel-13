export function inBrazil(lon: number, lat: number) {
  let inside = false
  for (let i = 0, j = BRAZIL.length - 1; i < BRAZIL.length; j = i++) {
    const a = BRAZIL[i]
    const b = BRAZIL[j]
    if (!a || !b) continue
    if (a[1] > lat !== b[1] > lat && lon < ((b[0] - a[0]) * (lat - a[1])) / (b[1] - a[1]) + a[0])
      inside = !inside
  }
  return inside
}

